import { z } from 'zod';

/** A latitude in degrees, north positive. */
export const Latitude = z.number().min(-90).max(90);

/** A longitude in degrees, east positive. */
export const Longitude = z.number().min(-180).max(180);

/** A three-letter upper-case IATA airport code. */
export const IataCode = z.string().regex(/^[A-Z]{3}$/);

/** An airport of the bundled list: enough for a transit report's airport cards and local times. */
export const Airport = z.object({
  iata: IataCode,
  name: z.string().min(1),
  city: z.string().min(1),
  country: z.string().min(1),
  lat: Latitude,
  lon: Longitude,
  /** IANA time zone, e.g. `Europe/London`. */
  timeZone: z.string().min(1),
});
export type Airport = z.infer<typeof Airport>;

