import type { ChatSession, ChatTurn } from '../../domain/chat/chat-session.js';
import type {
  ChatRenderer,
  RenderChatRendererRequest,
  RenderChatRendererResponse,
} from '../../domain/render/chat-renderer.js';

/** One Markdown document: contents first, then every session with its conversation. */
export class MarkdownChatRenderer implements ChatRenderer {
  render(req: RenderChatRendererRequest): RenderChatRendererResponse {
    const parts = [
      '# AI chat',
      'Claude Code sessions of this repository (main checkout and every worktree), oldest first. ' +
        'Only the conversation is shown: prompts, replies, questions with their answers and ' +
        'subagents; tool calls, tool output and thinking are left out. Generated by ' +
        '`npm run export:chats`.',
      '## Contents',
      req.sessions
        .map((s) => `- ${this.date(s)} · ${s.worktree} · [${s.title}](#${this.anchor(s)})`)
        .join('\n'),
      ...req.sessions.map((s) => this.session(s)),
    ];
    return { markdown: `${parts.join('\n\n')}\n` };
  }

  private session(session: ChatSession): string {
    return [
      `<a id="${this.anchor(session)}"></a>`,
      `## ${session.title}`,
      `${this.date(session)} · worktree \`${session.worktree}\` · session \`${session.id}\``,
      ...session.turns.map((turn) => this.turn({ turn, level: 3 })),
    ].join('\n\n');
  }

  private turn(req: { turn: ChatTurn; level: number }): string {
    const heading = '#'.repeat(req.level);
    const { turn } = req;
    switch (turn.kind) {
      case 'prompt':
        return `${heading} User\n\n${turn.text}`;
      case 'reply':
        return `${heading} Claude\n\n${turn.text}`;
      case 'questions':
        return `${heading} Claude asked\n\n${turn.items
          .map(
            (item) =>
              `- **${item.question}** → ${item.answer === '' ? '_no answer_' : item.answer}`,
          )
          .join('\n')}`;
      case 'subagent':
        return [
          '<details>',
          `<summary>Subagent ${turn.agentType}: ${turn.description}</summary>`,
          ...turn.turns.map((inner) => this.turn({ turn: inner, level: req.level + 1 })),
          '</details>',
        ].join('\n\n');
    }
  }

  private anchor(session: ChatSession): string {
    return `session-${session.id}`;
  }

  private date(session: ChatSession): string {
    return `${session.startedAt.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
  }
}
